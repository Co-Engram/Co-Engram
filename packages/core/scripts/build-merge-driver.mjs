#!/usr/bin/env node
/**
 * Build standalone merge-driver bundle.
 *
 * Output: dist/merge-driver.js (single CJS file, all deps inlined).
 * Banner contains the version so onboard can detect upgrades.
 */

import { build } from "esbuild";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const pkg = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const version = pkg.version;

const entry = resolve(root, "src/merge/driver-main.ts");
const outfile = resolve(root, "dist/merge-driver.cjs");

await build({
  entryPoints: [entry],
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node22",
  outfile,
  minify: false,
  sourcemap: false,
  banner: {
    js: `// co-engram-merge-driver v${version}\n// Auto-generated by pnpm build:merge-driver. Do not edit by hand.`,
  },
  external: [],
});

console.log(`[merge-driver] bundle written to ${outfile} (v${version})`);
